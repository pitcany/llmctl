"""Systemd unit generation for session persistence.

Renders ready-to-install systemd unit files so a launched runtime survives a
reboot. Two flavors are supported:

* :func:`render_api_unit` — a service unit for the Mission Control API itself.
* :func:`render_session_unit` — a per-session unit that relaunches a model's
  runtime. For process runtimes (vLLM, llama.cpp, python scripts) it embeds the
  exact launch command and environment from the session's launch plan. For
  shared-daemon runtimes (Ollama, LM Studio) it emits the unit plus a warning
  pointing at the daemon's own service.

Generation is pure string rendering: nothing is written to disk or enabled here.
"""

from __future__ import annotations

import getpass
import os
import shlex
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from llmctl.config import ManagedUnitConfig, Settings, load_settings
from llmctl.db import RuntimeName, SessionKind
from llmctl.schemas import Session
from llmctl.services.sessions import AdoptError

#: Runtimes that run as their own managed daemons; a per-session process unit
#: does not apply (their own service should be enabled instead).
SERVER_RUNTIMES = {RuntimeName.OLLAMA, RuntimeName.LMSTUDIO}


@dataclass
class SystemdUnit:
    """A rendered systemd unit plus install guidance."""

    name: str
    content: str
    user: bool = True
    warnings: list[str] = field(default_factory=list)

    def install_commands(self) -> list[str]:
        """Return the shell commands to install and enable this unit."""
        if self.user:
            unit_dir = "~/.config/systemd/user"
            return [
                f"mkdir -p {unit_dir}",
                f"cat > {unit_dir}/{self.name} <<'EOF'\n{self.content}EOF",
                "systemctl --user daemon-reload",
                f"systemctl --user enable --now {self.name}",
            ]
        unit_dir = "/etc/systemd/system"
        return [
            f"sudo tee {unit_dir}/{self.name} > /dev/null <<'EOF'\n{self.content}EOF",
            "sudo systemctl daemon-reload",
            f"sudo systemctl enable --now {self.name}",
        ]


def _wanted_by(user: bool) -> str:
    """Return the appropriate ``WantedBy`` target for the unit scope."""
    return "default.target" if user else "multi-user.target"


def render_api_unit(settings: Settings | None = None, *, user: bool = True) -> SystemdUnit:
    """Render a systemd unit that runs the Mission Control API server."""
    cfg = settings or load_settings()
    scope = "user" if user else "system"
    cwd = str(Path.home())
    content = (
        f"# llm-mission-control.service ({scope} scope)\n"
        f"# Generated by `llmctl generate-systemd`.\n"
        "[Unit]\n"
        "Description=LLM Mission Control API\n"
        "After=network-online.target\n"
        "Wants=network-online.target\n"
        "\n"
        "[Service]\n"
        "Type=simple\n"
        f"WorkingDirectory={cwd}\n"
        f"ExecStart=llmctl serve --host {cfg.api.host} --port {cfg.api.port}\n"
        "Restart=on-failure\n"
        "RestartSec=5\n"
        "\n"
        "[Install]\n"
        f"WantedBy={_wanted_by(user)}\n"
    )
    unit = SystemdUnit(name="llm-mission-control.service", content=content, user=user)
    if cfg.api.host not in ("127.0.0.1", "localhost") and not cfg.scheduler.allow_public_bind:
        unit.warnings.append(
            f"api.host is {cfg.api.host} but scheduler.allow_public_bind is off: "
            "`llmctl serve` will refuse this bind and the unit will fail to "
            "start. Set scheduler.allow_public_bind=true or use a loopback host."
        )
    return unit


def launcher_path() -> Path:
    """The vLLM launcher script llmctl ships (``llmctl/data/vllm-launcher.sh``).

    The unit from :func:`render_vllm_unit` points ``ExecStart`` here, and
    ``ManagedUnitConfig.launcher_marker`` (``vllm-launcher.sh``) is what the
    adapter's legacy-unit guard looks for in ``systemctl cat``.
    """
    path = Path(__file__).resolve().parent.parent / "data" / "vllm-launcher.sh"
    if not path.is_file():
        raise FileNotFoundError(f"llmctl's vLLM launcher is missing: {path}")
    return path


def render_vllm_unit(
    managed_unit: ManagedUnitConfig,
    *,
    user_name: str | None = None,
    launcher: Path | None = None,
) -> SystemdUnit:
    """Render the system-scope unit ``llmctl run`` drives for ``managed_unit``.

    ``ExecStart`` is the shipped launcher, ``EnvironmentFile`` the path
    :meth:`ManagedUnitConfig.resolve_env_file` gives (prefixed ``-`` so the
    unit loads before the first swap has written it). The unit runs as the
    invoking user, which is who owns the Python env vLLM is installed in.
    """
    launcher = launcher or launcher_path()
    user_name = user_name or getpass.getuser()
    env_file = managed_unit.resolve_env_file()
    name = managed_unit.unit_name
    content = (
        f"# {name}.service (system scope)\n"
        f"# Generated by `llmctl install-vllm-unit`. `llmctl run <preset>` rewrites\n"
        f"# {env_file} and restarts this unit.\n"
        "[Unit]\n"
        f"Description=vLLM ({name}), managed by llmctl\n"
        "After=network-online.target\n"
        "Wants=network-online.target\n"
        "StartLimitIntervalSec=1800\n"
        "StartLimitBurst=3\n"
        "\n"
        "[Service]\n"
        "Type=simple\n"
        f"User={user_name}\n"
        f"EnvironmentFile=-{env_file}\n"
        f"ExecStart={launcher}\n"
        "Restart=on-failure\n"
        "RestartSec=15\n"
        "TimeoutStartSec=900\n"
        "KillMode=mixed\n"
        "TimeoutStopSec=60\n"
        f"SyslogIdentifier={name}\n"
        "\n"
        "[Install]\n"
        "WantedBy=multi-user.target\n"
    )
    unit = SystemdUnit(name=f"{name}.service", content=content, user=False)
    if managed_unit.launcher_marker and managed_unit.launcher_marker not in str(launcher):
        unit.warnings.append(
            f"managed_units launcher_marker is {managed_unit.launcher_marker!r} but the "
            f"shipped launcher is {launcher.name}; `llmctl run` would refuse this unit. "
            "Set launcher_marker to 'vllm-launcher.sh' (the default) or null."
        )
    return unit


def _escape_specifiers(text: str) -> str:
    """Escape systemd ``%`` specifiers so ``%h``-like text stays literal."""
    return text.replace("%", "%%")


def _environment_line(key: str, value: object) -> str:
    """Render one ``Environment=`` assignment, quoted for systemd.

    Unquoted, a value with a space split into two assignments (the second
    one a bogus ``KEY``-less word) and ``%`` was expanded as a specifier.
    Newlines cannot be represented in one directive, so they are refused.
    """
    text = f"{key}={value}"
    if "\n" in text or "\r" in text:
        raise ValueError(f"environment variable {key!r} contains a newline")
    escaped = _escape_specifiers(text.replace("\\", "\\\\").replace('"', '\\"'))
    return f'Environment="{escaped}"'


def _exec_command(parts: list[str]) -> str:
    """Join argv for ``ExecStart=``: shell-style quoting plus systemd escapes.

    systemd expands ``$VAR`` and ``%`` specifiers inside ExecStart even in
    quoted words, so both are doubled after ``shlex.quote``.
    """
    return " ".join(
        _escape_specifiers(shlex.quote(str(part))).replace("$", "$$") for part in parts
    )


def render_session_unit(
    session: Session,
    *,
    user: bool = True,
    working_dir: str | None = None,
) -> SystemdUnit:
    """Render a systemd unit that relaunches ``session``'s runtime on boot.

    Refuses for ``ADOPTED`` sessions: they have no llmctl-issued launch
    command, only a pointer to an externally-managed systemd unit (e.g.
    ``vllm-tp.service``), so generating a unit for them would emit a
    nonsense ``llmctl start None`` placeholder. The caller should
    install the upstream unit directly.
    """
    if session.kind == SessionKind.ADOPTED:
        target = session.systemd_unit or session.endpoint_url or "the upstream unit"
        raise AdoptError(
            f"Session {session.id} is adopted ({target}); llmctl does not own its "
            "launch command. Install the existing systemd unit directly "
            f"(e.g. `sudo systemctl enable {session.systemd_unit or '<unit>'}`)."
        )
    warnings: list[str] = []
    plan = session.launch_plan
    runtime = session.runtime
    short_id = (session.id or "session")[:8]
    label = session.launch_plan.model_name if plan and plan.model_name else session.model_id

    env_lines: list[str] = []
    if plan and plan.env:
        for key, value in plan.env.items():
            env_lines.append(_environment_line(key, value))

    if runtime in SERVER_RUNTIMES:
        warnings.append(
            f"{runtime.value} runs as a shared daemon; enable its own service "
            f"(e.g. `systemctl enable {runtime.value}`) for true persistence. "
            "This unit re-applies the session plan via llmctl."
        )
        exec_start = _exec_command(["llmctl", "start", str(session.model_id), "--no-dry-run"])
    elif plan and plan.command:
        exec_start = _exec_command(list(plan.command))
    else:
        warnings.append(
            "Session has no stored launch command; falling back to `llmctl start`."
        )
        exec_start = _exec_command(["llmctl", "start", str(session.model_id), "--no-dry-run"])

    # Generation-time cwd, not $HOME: relative script/model paths in the
    # stored launch command were validated against this cwd.
    cwd = working_dir or os.getcwd()
    name = f"llmctl-session-{short_id}.service"
    env_block = ("".join(f"{line}\n" for line in env_lines)) if env_lines else ""
    content = (
        f"# {name}\n"
        f"# Generated by `llmctl generate-systemd-session {session.id}`.\n"
        "[Unit]\n"
        f"Description=LLM Mission Control session {short_id} "
        f"({runtime.value} {_escape_specifiers(str(label or ''))})\n"
        "After=network-online.target\n"
        "Wants=network-online.target\n"
        "\n"
        "[Service]\n"
        "Type=simple\n"
        f"WorkingDirectory={cwd}\n"
        f"{env_block}"
        f"ExecStart={exec_start}\n"
        "Restart=on-failure\n"
        "RestartSec=5\n"
        "\n"
        "[Install]\n"
        f"WantedBy={_wanted_by(user)}\n"
    )
    return SystemdUnit(name=name, content=content, user=user, warnings=warnings)


@dataclass
class InstallReport:
    """Result of installing (or planning to install) a systemd unit."""

    unit_path: str
    actions: list[str]
    written: bool
    enabled: bool
    dry_run: bool
    messages: list[str] = field(default_factory=list)


def unit_install_path(unit: SystemdUnit) -> Path:
    """Return the on-disk location a unit would be installed to."""
    if unit.user:
        return Path("~/.config/systemd/user").expanduser() / unit.name
    return Path("/etc/systemd/system") / unit.name


def _systemctl_prefix(user: bool) -> list[str]:
    """Return the ``systemctl`` invocation prefix for the unit scope."""
    return ["systemctl", "--user"] if user else ["sudo", "systemctl"]


def install_unit(
    unit: SystemdUnit, *, dry_run: bool = False, enable: bool = True
) -> InstallReport:
    """Write a unit to disk and reload/enable it via systemctl.

    With ``dry_run`` nothing is written or executed; the report lists the actions
    that *would* run. systemd absence (e.g. inside a container) is handled
    gracefully: a user unit file is still written and a clear message is
    recorded. A system-scope unit is written with ``sudo tee``.
    """
    path = unit_install_path(unit)
    systemctl = _systemctl_prefix(unit.user)
    write = f"write unit -> {path}" if unit.user else f"sudo tee {path}"
    actions = [write, " ".join([*systemctl, "daemon-reload"])]
    if enable:
        actions.append(" ".join([*systemctl, "enable", "--now", unit.name]))

    if dry_run:
        return InstallReport(
            unit_path=str(path),
            actions=actions,
            written=False,
            enabled=False,
            dry_run=True,
            messages=["Dry run: no changes were made."],
        )

    messages: list[str] = []
    enabled = False
    try:
        if unit.user:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(unit.content, encoding="utf-8")
        else:
            # /etc/systemd/system is root's; write through sudo like the
            # start/stop/restart calls the unit will later get.
            subprocess.run(
                ["sudo", "tee", str(path)],
                input=unit.content,
                check=True,
                capture_output=True,
                text=True,
            )
        subprocess.run(
            [*systemctl, "daemon-reload"], check=True, capture_output=True, text=True
        )
        if enable:
            subprocess.run(
                [*systemctl, "enable", "--now", unit.name],
                check=True,
                capture_output=True,
                text=True,
            )
            enabled = True
        messages.append(f"Installed {unit.name} ({'enabled' if enabled else 'written'}).")
    except FileNotFoundError:
        messages.append(
            "systemctl not found; wrote the unit file but could not reload/enable it."
        )
    except subprocess.CalledProcessError as exc:
        detail = (exc.stderr or "").strip() or str(exc)
        messages.append(f"systemctl failed: {detail}")
    return InstallReport(
        unit_path=str(path),
        actions=actions,
        written=True,
        enabled=enabled,
        dry_run=False,
        messages=messages,
    )
